/* ============================================================
   EMBED APTOS NARROW INTO THE PDF GENERATOR
   --------------------------------------------------------------
   Usage:
     npm run embed-font                       (finds the font on this machine)
     npm run embed-font -- <regular.ttf> <bold.ttf>

   Aptos Narrow ships with Microsoft 365, so any machine with Office installed
   has it in C:\Windows\Fonts. This reads the two weights the invoice uses and
   writes them into src/fonts/aptosNarrow.js as base64, which is the only way
   jsPDF can carry a typeface that is not one of the 14 standard PDF fonts.
   ============================================================ */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { basename, join, resolve } from 'path';

const OUT = resolve('src/fonts/aptosNarrow.js');

const FONT_DIRS = [
  process.env.WINDIR ? join(process.env.WINDIR, 'Fonts') : 'C:/Windows/Fonts',
  process.env.LOCALAPPDATA ? join(process.env.LOCALAPPDATA, 'Microsoft/Windows/Fonts') : null,
  '/Library/Fonts',
  process.env.HOME ? join(process.env.HOME, 'Library/Fonts') : null,
  '/usr/share/fonts/truetype'
].filter(Boolean);

/** Aptos Narrow, however the installer happened to name the file. */
const NARROW_RE = /aptos[-_ ]?narrow/i;
const BOLD_RE = /bold/i;
const ITALIC_RE = /italic|oblique/i;

function discover() {
  const found = [];
  for (const dir of FONT_DIRS) {
    if (!existsSync(dir)) continue;
    let entries = [];
    try { entries = readdirSync(dir); } catch { continue; }
    for (const name of entries) {
      if (!/\.ttf$/i.test(name)) continue;
      if (!NARROW_RE.test(name)) continue;
      if (ITALIC_RE.test(name)) continue;
      found.push(join(dir, name));
    }
  }
  const bold = found.find((f) => BOLD_RE.test(basename(f))) || '';
  const regular = found.find((f) => !BOLD_RE.test(basename(f))) || '';
  return { regular, bold, found };
}

/** A TrueType/OpenType file starts with one of these signatures. */
function assertFont(path) {
  const buf = readFileSync(path);
  const tag = buf.subarray(0, 4).toString('hex');
  const ok = ['00010000', '74727565', '4f54544f', '74746366'].includes(tag);
  if (!ok) throw new Error(path + ' is not a TrueType/OpenType font (magic ' + tag + ')');
  return buf;
}

const args = process.argv.slice(2).filter((a) => a !== '--');
let regularPath = args[0] || '';
let boldPath = args[1] || '';

if (!regularPath) {
  const hit = discover();
  regularPath = hit.regular;
  boldPath = boldPath || hit.bold;
  if (!regularPath) {
    console.error('Could not find Aptos Narrow on this machine.\n');
    console.error('Looked in:\n  ' + FONT_DIRS.join('\n  '));
    console.error('\nCopy AptosNarrow.ttf and AptosNarrow-Bold.ttf off a machine that has');
    console.error('Microsoft 365 installed (they live in C:\\Windows\\Fonts), then run:');
    console.error('  npm run embed-font -- path\\to\\AptosNarrow.ttf path\\to\\AptosNarrow-Bold.ttf');
    process.exit(1);
  }
  console.log('Found: ' + regularPath + (boldPath ? '\n       ' + boldPath : ''));
}

const regular = assertFont(resolve(regularPath));
const bold = boldPath ? assertFont(resolve(boldPath)) : null;
if (!bold) console.warn('No bold weight given — bold text will reuse the regular file.');

const header = `/* ============================================================
   APTOS NARROW — PDF FONT DATA
   --------------------------------------------------------------
   AUTO-GENERATED by scripts/embed-pdf-font.mjs — do not edit by hand.
   Regenerate with: npm run embed-font

   Source files:
     regular: ${basename(regularPath)}
     bold:    ${bold ? basename(boldPath) : '(none — regular reused)'}

   jsPDF only ships the 14 standard PDF fonts, so Aptos Narrow has to travel
   inside the document as base64. Word gets the same typeface by name, through
   docxShared.RUN_FONT.
   ============================================================ */

`;

const body =
  'export const APTOS_NARROW_REGULAR = \'' + regular.toString('base64') + '\';\n\n' +
  'export const APTOS_NARROW_BOLD = \'' + (bold || regular).toString('base64') + '\';\n';

writeFileSync(OUT, header + body);
const kb = (n) => Math.round(n / 1024) + ' KB';
console.log('Wrote ' + OUT);
console.log('  regular ' + kb(regular.length) + ' → base64 ' + kb(regular.toString('base64').length));
console.log('  bold    ' + kb((bold || regular).length));
console.log('\nRebuild (npm run build) and the invoice + proforma PDFs will render in Aptos Narrow.');
